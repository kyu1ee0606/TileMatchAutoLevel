#!/usr/bin/env python3
"""Extract the t0-shuffle code path from the game client's DB_Level.cs, verbatim, by line range.

Output: Generated/DB_Level.Extract.g.cs (compiled by PvGolden.csproj) + Generated/extract_meta.json.

Rules
- The original file is pinned by sha256 (EXPECTED_SHA256). Any change -> exit 1 (re-verify ranges, then update the pin).
- Every segment's first line is checked against an anchor string (guards against wrong ranges after a re-pin).
- Segment text is copied byte-for-byte; `#line` directives map compile errors back to the original file.
- distVer = "cs:" + sha256(GetEmptyTileList + GetToAddIndexList + ShuffleEmptyTiles + DistributeTiles
  segment bytes, in that order, + zWellRandom.cs bytes)[:12]   (04 plan A3-5)
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DB_LEVEL_REL = "Assets/08.Scripts/Tile_Script/InGame/DB_Level.cs"
ZWELL_REL = "Assets/00.spComponents/zWellRandom.cs"

# game repo commit b741f6a3 (2026-09-21), the last commit touching DB_Level.cs
EXPECTED_SHA256 = "b76a2e014aca4823f53b8078671550a77bb5d2e1018b0f55c03cf69abc6c586b"
EXPECTED_ZWELL_SHA256 = "af9ad44037ae5d1cf4324fdfea0e93ec7a9c8ff444df53d9d389c99b8478744c"

# (name, first_line, last_line inclusive, 1-based, anchor substring of first line, container)
SEGMENTS = [
    ("CTileStackInfo", 137, 213, "public class CTileStackInfo", "DB_Level"),
    ("CTile", 219, 381, "public class CTile", "DB_Level"),
    ("CTileList", 383, 497, "public class CTileList : Dictionary<string, CTile>", "DB_Level"),
    ("CLayer", 503, 513, "public class CLayer", "DB_Level"),
    ("CLayerList", 515, 572, "public class CLayerList : Dictionary<string, CLayer>", "DB_Level"),
    ("CLevel.fields+EffectiveLayerCount", 580, 630, "public spEncrypt xID;", "CLevel"),
    ("CLevel.GetUsingTileCount", 865, 868, "public int GetUsingTileCount()", "CLevel"),
    ("CLevel.GetEmptyTileList", 870, 945, "public List<CTile> GetEmptyTileList(bool getAllTile = false)", "CLevel"),
    ("CLevelList.GetToAddIndexList", 1123, 1156, "public List<int> GetToAddIndexList(CLevel cLevel)", "CLevelList"),
    ("CLevelList.randomTileIndexList", 1160, 1160, "[SerializeField] List<int> randomTileIndexList", "CLevelList"),
    ("CLevelList.ShuffleEmptyTiles", 1167, 1292, "public void ShuffleEmptyTiles(CLevel cLevel)", "CLevelList"),
    ("CLevelList.ApplyVisualTileRemap", 1307, 1354, "private void ApplyVisualTileRemap(CLevel cLevel, List<CTile> emptyTiles)", "CLevelList"),
    ("CLevelList.DistributeTiles+helpers", 1356, 1502, "private float ImbalanceFactor = 3.0f;", "CLevelList"),
    ("CLevelList.UpdateNewMapData", 1538, 1614, "public void UpdateNewMapData(JSONNode levelJSON)", "CLevelList"),
    ("CLevelList.GetLevel+SetLevel", 1616, 1633, "public CLevel GetLevel(string sLevelID)", "CLevelList"),
]

DIST_VER_SEGMENTS = [
    "CLevel.GetEmptyTileList",
    "CLevelList.GetToAddIndexList",
    "CLevelList.ShuffleEmptyTiles",
    "CLevelList.DistributeTiles+helpers",
]

HEADER = """// <auto-generated>
// VERBATIM line-range extraction of {src} by tools/pv_golden/extract_methods.py.
// Do not edit. Source sha256 {sha}. Regenerated on every build.
// Only the class headers / using lines below are written by the extractor.
// </auto-generated>
using System.Collections;
using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using SimpleJSON;
using System;

public partial class DB_Level : MonoBehaviour
{{
"""


def sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--game-repo", default=str(HERE.parent.parent.parent / "sp_meowsgarden"))
    ap.add_argument("--out-dir", default=str(HERE / "Generated"))
    args = ap.parse_args()

    game = Path(args.game_repo).resolve()
    src = game / DB_LEVEL_REL
    zwell = game / ZWELL_REL
    raw = src.read_bytes()
    zraw = zwell.read_bytes()

    sha = sha256_bytes(raw)
    zsha = sha256_bytes(zraw)
    errors = []
    if sha != EXPECTED_SHA256:
        errors.append(f"DB_Level.cs sha256 changed: {sha} != pinned {EXPECTED_SHA256}")
    if zsha != EXPECTED_ZWELL_SHA256:
        errors.append(f"zWellRandom.cs sha256 changed: {zsha} != pinned {EXPECTED_ZWELL_SHA256}")
    if b"\r\n" in raw:
        errors.append("DB_Level.cs has CRLF line endings (unexpected; segment hashing assumes LF)")

    lines = raw.split(b"\n")  # keep exact bytes; re-joined with b"\n"
    segs = {}
    for name, a, b, anchor, container in SEGMENTS:
        seg_lines = lines[a - 1:b]
        first = seg_lines[0].decode("utf-8")
        if anchor not in first:
            errors.append(f"segment {name}: line {a} does not contain anchor {anchor!r}: {first.strip()!r}")
        text = b"\n".join(seg_lines) + b"\n"
        segs[name] = (a, b, container, text)

    if errors:
        for e in errors:
            print("extract_methods.py: ERROR " + e, file=sys.stderr)
        return 1

    dist_material = b"".join(segs[n][3] for n in DIST_VER_SEGMENTS) + zraw
    dist_ver = "cs:" + sha256_bytes(dist_material)[:12]

    src_abs = str(src).replace("\\", "/")
    out = [HEADER.format(src=DB_LEVEL_REL, sha=sha)]
    open_container = "DB_Level"

    def close():
        if open_container != "DB_Level":
            out.append("#line default\n}\n")

    for name, a, b, anchor, container in SEGMENTS:
        if container != open_container:
            close()
            if container == "CLevel":
                out.append("public class CLevel\n{\n")
            elif container == "CLevelList":
                out.append("public class CLevelList : Dictionary<string, CLevel>\n{\n")
            open_container = container
        out.append(f"#line {a} \"{src_abs}\"\n")
        out.append(segs[name][3].decode("utf-8"))
        out.append("#line default\n")
    close()
    out.append("}\n")

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    gen = "".join(out)
    (out_dir / "DB_Level.Extract.g.cs").write_text(gen, encoding="utf-8")

    meta = {
        "source": DB_LEVEL_REL,
        "sourceSha256": sha,
        "zWellRandom": ZWELL_REL,
        "zWellRandomSha256": zsha,
        "sourceCommit": "b741f6a3",
        "distVer": dist_ver,
        "distVerDefinition": "cs:+sha256(" + "+".join(DIST_VER_SEGMENTS) + "+zWellRandom.cs)[:12]; segment = original lines joined with LF + trailing LF",
        "segments": [
            {"name": n, "lines": [segs[n][0], segs[n][1]], "sha256": sha256_bytes(segs[n][3])}
            for n, *_ in SEGMENTS
        ],
    }
    (out_dir / "extract_meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"extract_methods.py: OK sha256={sha[:12]} distVer={dist_ver}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
